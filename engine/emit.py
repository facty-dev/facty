#!/usr/bin/env python3
# emit.py — codegen projections: canonical JSON schemas/rules → TypeScript
# types + Datalog. ADR-0003 §2: one schema, three projections. The third
# (JSONB rows) arrives with Postgres, when a database is actually required.
#
# Usage:
#   python3 engine/emit.py

import json
from pathlib import Path

ENGINE_DIR = Path(__file__).resolve().parent
SCHEMA_DIR = ENGINE_DIR / "schemas"
OUT_DIR = ENGINE_DIR / "emit"

TS_SCALARS = {"string": "string", "number": "number", "integer": "number", "boolean": "boolean"}


def ts_type(prop):
    if "enum" in prop:
        return " | ".join(json.dumps(v) for v in prop["enum"])
    t = prop.get("type")
    if t == "array":
        return ts_type(prop.get("items", {})) + "[]"
    if t == "object":
        return "Record<string, unknown>"
    return TS_SCALARS.get(t, "unknown")


def emit_ts():
    parts = ["// Generated by engine/emit.py — do not edit by hand.",
             "// Projection: canonical JSON schemas → TypeScript types.",
             ""]
    for schema_file in sorted(SCHEMA_DIR.glob("*.schema.json")):
        schema = json.loads(schema_file.read_text())
        name = schema.get("title", schema_file.stem.replace(".schema", ""))
        parts.append(f"export interface {name} {{")
        for key, prop in schema.get("properties", {}).items():
            optional = "" if key in schema.get("required", []) else "?"
            parts.append(f"  {key}{optional}: {ts_type(prop)};")
        parts.append("}")
        parts.append("")
    return "\n".join(parts)


def datalog_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(str(v))


def emit_datalog(case_dir):
    rules = json.loads((Path(case_dir) / "pack" / "rules.json").read_text())
    lines = ["// Generated by engine/emit.py — do not edit by hand.",
             "// Projection: canonical rules → Datalog (Soufflé-compatible sketch).",
             ""]
    for rule in rules:
        for action in rule["then"]:
            if action.get("op") != "derive":
                continue
            fact = action["fact"]
            head = (f"fact({datalog_value(fact['subject'])}, "
                    f"{datalog_value(fact['predicate'])}, "
                    f"{datalog_value(fact['value'])}).")
            body = ", ".join(
                f"fact({datalog_value(c['subject'])}, {datalog_value(c['predicate'])}, "
                f"{datalog_value(c['value'])})"
                for c in rule["when"]
                if "subject" in c and "predicate" in c and "value" in c
            )
            lines.append(f"{head} :- {body}." if body else head)
            lines.append("")
    return "\n".join(lines)


def main():
    OUT_DIR.mkdir(exist_ok=True)
    ts = emit_ts()
    dl = emit_datalog(ENGINE_DIR / "cases" / "silver-blaze")
    (OUT_DIR / "types.ts").write_text(ts)
    (OUT_DIR / "rules.dl").write_text(dl)
    print(f"emitted: {OUT_DIR / 'types.ts'} ({len(ts.splitlines())} lines)")
    print(f"emitted: {OUT_DIR / 'rules.dl'} ({len(dl.splitlines())} lines)")


if __name__ == "__main__":
    main()
