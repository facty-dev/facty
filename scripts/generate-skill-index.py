#!/usr/bin/env python3
# generate-skill-index.py — regenerate gondolin/skills/SKILL-INDEX.md
# from the vendored SKILL.md frontmatter (name + description).
#
# The index is baked into the gondolin image; pi links it as the skill
# catalog. Run this after adding or removing skills under gondolin/skills/.
#
# Usage: python3 scripts/generate-skill-index.py

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKILLS = REPO / "gondolin" / "skills"
INDEX = SKILLS / "SKILL-INDEX.md"


def frontmatter(path):
    """The YAML-ish frontmatter of a SKILL.md (name + description)."""
    text = path.read_text()
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    if not m:
        return {}
    fm = {}
    key = None
    for line in m.group(1).splitlines():
        if line.startswith((" ", "\t")) and key:
            fm[key] += " " + line.strip()  # folded continuation
        elif re.match(r"^[a-z_]+:", line):
            key, _, value = line.partition(":")
            fm[key] = "" if value.strip() in (">", "|") else value.strip()
    return fm


def main():
    rows = []
    for skill_md in sorted(SKILLS.glob("*/SKILL.md")):
        fm = frontmatter(skill_md)
        name = fm.get("name") or skill_md.parent.name
        desc = re.sub(r"\s+", " ", fm.get("description", "")).strip()
        if len(desc) > 160:
            desc = desc[:157].rstrip() + "…"
        rows.append((name, desc))
    lines = [
        "# Skill Index — the Facty VM skill set",
        "",
        "Generated by `scripts/generate-skill-index.py` — run it after",
        "adding or removing skills under `gondolin/skills/`. The index is",
        "baked into the gondolin image; pi links it as the skill catalog.",
        "",
        f"**Skills:** {len(rows)}",
        "",
        "| # | Skill | Description |",
        "|---|---|---|",
    ]
    for i, (name, desc) in enumerate(rows, 1):
        lines.append(f"| {i} | `{name}` | {desc} |")
    INDEX.write_text("\n".join(lines) + "\n")
    print(f"indexed {len(rows)} skills → {INDEX.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
