#!/usr/bin/env bash
# sdlc-branch.sh — Manage SDLC branches locally.
#
# Simulates the Git-native pipeline locally:
#   - Create phase branches
#   - Run agents (in the SDLC VM session)
#   - Merge with skip-ahead detection
#   - Sync asset graph
#
# Usage:
#   ./scripts/sdlc-branch.sh start <feature-slug>       # Start new SDLC
#   ./scripts/sdlc-branch.sh branch <phase> <slug>       # Create phase branch
#   ./scripts/sdlc-branch.sh merge <phase> <slug>        # Merge with triggers
#   ./scripts/sdlc-branch.sh status <slug>               # Show SDLC status
#   ./scripts/sdlc-branch.sh inject <phase> <slug> <file> # Human injection
#   ./scripts/sdlc-branch.sh list                         # List all SDLC branches

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

# ── Colors ───────────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

info()    { echo -e "${BLUE}ℹ${NC} $*"; }
ok()      { echo -e "${GREEN}✓${NC} $*"; }
warn()    { echo -e "${YELLOW}⚠${NC} $*"; }
err()     { echo -e "${RED}✗${NC} $*" >&2; }
section() { echo ""; echo -e "${CYAN}━━━ $* ━━━${NC}"; }

# ── Config ───────────────────────────────────────────────────────────────────
PHASES=("ost" "prd" "bdd" "impl")
PHASE_NAMES=("Discovery" "Define" "Develop" "Deliver")
PHASE_AGENTS=("decision" "decision" "decision" "coding")

# Get next phase
next_phase() {
  local current="$1"
  case "$current" in
    ost)  echo "prd" ;;
    prd)  echo "bdd" ;;
    bdd)  echo "impl" ;;
    impl) echo "done" ;;
    *)    echo "unknown" ;;
  esac
}

# Get phase number (0-indexed)
phase_num() {
  local phase="$1"
  case "$phase" in
    ost)  echo "0" ;;
    prd)  echo "1" ;;
    bdd)  echo "2" ;;
    impl) echo "3" ;;
    *)    echo "-1" ;;
  esac
}

# Check if asset exists for phase
asset_exists() {
  local phase="$1"
  local slug="$2"
  case "$phase" in
    ost)  [[ -f "docs/discovery/ost.md" ]] || ls docs/discovery/*ost* &>/dev/null ;;
    prd)  ls docs/prd/*"$slug"* &>/dev/null || ls docs/prd/PRD-*.md &>/dev/null ;;
    bdd)  ls specs/features/ &>/dev/null ;;
    impl) ls src/ &>/dev/null || ls tests/ &>/dev/null ;;
    *)    return 1 ;;
  esac
}

# ── Commands ─────────────────────────────────────────────────────────────────

cmd_start() {
  local slug="$1"
  [[ -z "$slug" ]] && { err "Usage: $0 start <feature-slug>"; exit 1; }

  section "Starting SDLC: $slug"

  # Create initial branch
  local branch="sdlc/ost/$slug"
  git checkout -b "$branch" main 2>/dev/null || git checkout "$branch"
  ok "Created branch: $branch"

  # Initialize directories
  mkdir -p docs/discovery docs/prd specs/features .agentic/messages/{decision-to-coding,coding-to-decision,human-review}

  # Create placeholder
  cat > docs/discovery/problems.md <<EOF
# Problems — $slug

*Generated: $(date +%Y-%m-%d)*

## Problem Statement

<!-- TODO: Add problem description -->
EOF

  git add -A
  git commit -m "chore: initialize SDLC for $slug [skip ci]"
  git push -u origin "$branch" 2>/dev/null || warn "Could not push (no remote?)"

  ok "SDLC initialized for: $slug"
  info "Next: ./scripts/sdlc-branch.sh agent ost $slug"
  info "  Or: make agent-decision PHASE=discovery TASK='Build OST for $slug'"
}

cmd_branch() {
  local phase="$1"
  local slug="$2"
  [[ -z "$phase" || -z "$slug" ]] && { err "Usage: $0 branch <phase> <slug>"; exit 1; }

  section "Creating branch: sdlc/$phase/$slug"

  local branch="sdlc/$phase/$slug"
  git checkout -b "$branch" main 2>/dev/null || git checkout "$branch"
  ok "On branch: $branch"

  # Create phase directory if needed
  case "$phase" in
    ost)  mkdir -p docs/discovery ;;
    prd)  mkdir -p docs/prd ;;
    bdd)  mkdir -p specs/features ;;
    impl) mkdir -p src tests docs/adr ;;
  esac
}

cmd_merge() {
  local phase="$1"
  local slug="$2"
  [[ -z "$phase" || -z "$slug" ]] && { err "Usage: $0 merge <phase> <slug>"; exit 1; }

  section "Merging sdlc/$phase/$slug → main"

  local branch="sdlc/$phase/$slug"

  # Check branch exists
  if ! git rev-parse --verify "$branch" &>/dev/null; then
    err "Branch not found: $branch"
    exit 1
  fi

  # Checkout main and merge
  git checkout main
  git merge --squash "$branch"
  git commit -m "feat($phase): merge $slug $phase

Merged from: $branch
Phase: $phase
Feature: $slug

🤖 Generated by agentic SDLC"
  ok "Merged: $branch → main"

  # Sync asset graph
  ./scripts/asset-sync.sh 2>/dev/null || warn "asset-sync.sh not ready"

  # Detect skip-ahead: check what assets exist now
  local trigger="done"
  local skip_ahead=()

  if asset_exists impl "$slug"; then
    trigger="done"
  elif asset_exists bdd "$slug"; then
    trigger="impl"
  elif asset_exists prd "$slug"; then
    trigger="bdd"
    [[ "$phase" != "prd" ]] && skip_ahead+=("prd")
  elif asset_exists ost "$slug"; then
    trigger="prd"
    [[ "$phase" != "ost" ]] && skip_ahead+=("ost")
  fi

  # Log audit event
  mkdir -p .agentic
  cat >> .agentic/audit.jsonl <<EOF
{
  "event_id": "evt-local-$(date +%s)",
  "timestamp": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "event_type": "pr.merged",
  "branch": "$branch",
  "phase": "$phase",
  "slug": "$slug",
  "trigger": "$trigger",
  "skip_ahead": [$(printf '"%s",' "${skip_ahead[@]}" | sed 's/,$//')]
}
EOF

  git add -A
  git commit -m "chore: update audit trail [skip ci]" || true

  # Trigger downstream
  if [[ "$trigger" != "done" && "$trigger" != "unknown" ]]; then
    if [[ ${#skip_ahead[@]} -gt 0 ]]; then
      warn "Skip-ahead detected: ${skip_ahead[*]}"
      info "Skipping directly to: $trigger"
    fi

    section "Triggering downstream: $trigger"
    info "Next: ./scripts/sdlc-branch.sh branch $trigger $slug"
    info "  Or: make agent-decision PHASE=$trigger TASK='Generate $trigger for $slug'"
  else
    ok "SDLC complete for: $slug"
  fi

  # Delete merged branch
  git branch -d "$branch" 2>/dev/null || true
}

cmd_inject() {
  local phase="$1"
  local slug="$2"
  local file="$3"
  [[ -z "$phase" || -z "$slug" || -z "$file" ]] && {
    err "Usage: $0 inject <phase> <slug> <file>"
    exit 1
  }

  section "Human injection: $file → sdlc/$phase/$slug"

  local branch="sdlc/$phase/$slug"
  git checkout "$branch" 2>/dev/null || {
    err "Branch not found: $branch"
    exit 1
  }

  # Copy file to appropriate location
  case "$phase" in
    ost)  cp "$file" docs/discovery/ ;;
    prd)  cp "$file" docs/prd/ ;;
    bdd)  cp "$file" specs/features/ ;;
    impl) cp "$file" src/ ;;
  esac

  git add -A
  git commit -m "docs: human injection — $file

Injected by: $(git config user.name)
Phase: $phase
Feature: $slug"
  git push 2>/dev/null || true

  ok "Injected: $file"
  info "On merge, this asset will be detected and may trigger skip-ahead"
}

cmd_status() {
  local slug="${1:-}"

  section "SDLC Status ${slug:+$slug}"

  # List all SDLC branches
  local branches
  branches=$(git branch -a | grep 'sdlc/' || true)

  if [[ -z "$branches" ]]; then
    info "No SDLC branches found"
  else
    echo "Branches:"
    echo "$branches" | sed 's/^/  /'
  fi

  echo ""
  echo "Merged assets (on main):"

  for phase in "${PHASES[@]}"; do
    local name="${PHASE_NAMES[$(phase_num "$phase")]}"
    local dir=""
    case "$phase" in
      ost)  dir="docs/discovery" ;;
      prd)  dir="docs/prd" ;;
      bdd)  dir="specs/features" ;;
      impl) dir="src" ;;
    esac

    if [[ -d "$dir" ]] && ls "$dir"/* &>/dev/null; then
      echo "  ✓ $name ($phase):"
      ls "$dir" | head -3 | sed 's/^/    - /'
      local count
      count=$(ls "$dir" | wc -l | tr -d ' ')
      [[ $count -gt 3 ]] && echo "    ... ($count total)"
    else
      echo "  ○ $name ($phase): (pending)"
    fi
  done

  # Show asset graph if exists
  if [[ -f assets/graph.json ]]; then
    echo ""
    echo "Asset graph: assets/graph.json"
    jq -r '.nodes | keys[]' assets/graph.json 2>/dev/null | sed 's/^/  - /' || true
  fi
}

cmd_list() {
  section "All SDLC branches"
  git branch -a | grep 'sdlc/' || echo "  (none)"
}

cmd_agent() {
  local phase="$1"
  local slug="$2"
  [[ -z "$phase" || -z "$slug" ]] && { err "Usage: $0 agent <phase> <slug>"; exit 1; }

  local agent="${PHASE_AGENTS[$(phase_num "$phase")]}"
  local branch="sdlc/$phase/$slug"

  section "Running $agent agent for $phase/$slug"

  git checkout "$branch" 2>/dev/null || {
    err "Branch not found: $branch (create with: $0 branch $phase $slug)"
    exit 1
  }

  info "Agent: $agent"
  info "Branch: $branch"
  info "Phase: $phase"
  echo ""
  info "Run agent for this phase:"
  echo "  make agent-$agent PHASE=$phase TASK='Generate $phase assets for $slug'"
}

# ── Main ─────────────────────────────────────────────────────────────────────
case "${1:-}" in
  start)   shift; cmd_start "$@" ;;
  branch)  shift; cmd_branch "$@" ;;
  merge)   shift; cmd_merge "$@" ;;
  inject)  shift; cmd_inject "$@" ;;
  status)  shift; cmd_status "$@" ;;
  list)    cmd_list ;;
  agent)   shift; cmd_agent "$@" ;;
  *)
    echo "Usage: $0 <command> [args]"
    echo ""
    echo "Commands:"
    echo "  start <slug>              Start new SDLC for a feature"
    echo "  branch <phase> <slug>     Create phase branch (ost|prd|bdd|impl)"
    echo "  merge <phase> <slug>      Merge phase branch with skip-ahead detection"
    echo "  inject <phase> <slug> <file>  Human injection of asset file"
    echo "  status [slug]             Show SDLC status"
    echo "  list                      List all SDLC branches"
    echo "  agent <phase> <slug>      Show agent command for phase"
    ;;
esac
